// What clang in the page needs besides itself to make a model's side module:
// the headers a model's C++ reads and Simile's support.cpp compiled once —
// written as a classic script for the page (src/engine-build.js):
//
//   window.SIMILE_MODEL_KIT = { files: {path: base64}, supportO: base64 }
//
//   node model-kit.mjs <@yowasp/clang gen/bundle.js> <simile src> <out .js>
//
// Every model's C++ includes the same three files (support1.cpp, support2.cpp,
// Functions/procs.cpp), so the header set is the one emcc reads for any model
// (emsdk's `em++ -M` on the predator-prey sample): ~170 files from emsdk's
// sysroot, laid out as the page's clang expects them — /sysroot, /simile, /stubs.
import fs from 'node:fs';
import path from 'node:path';
import { execFileSync } from 'node:child_process';

const [bundle, simileSrc, out] = process.argv.slice(2);
if (!out) { console.error('usage: model-kit.mjs <yowasp bundle.js> <simile src> <out .js>'); process.exit(2); }
const { runClang } = await import(path.resolve(bundle));
const SRC = path.resolve(simileSrc);
const HERE = path.dirname(new URL(import.meta.url).pathname);
const STUBS = path.join(HERE, '../stubs');
const SYS = process.env.HOME + '/emsdk/upstream/emscripten/cache/sysroot';
const EMXX = process.env.HOME + '/emsdk/upstream/emscripten/em++';

const tmp = fs.mkdtempSync(path.join(path.dirname(path.resolve(out)), '.kit-'));
try {
  const sample = fs.readFileSync(path.join(HERE, '../predator-prey.cpp.sample'), 'utf8')
    .replace(/#include "[^"]*\/Functions\/procs\.cpp"/, '#include "' + SRC + '/Functions/procs.cpp"');
  fs.writeFileSync(path.join(tmp, 'model.cpp'), sample);
  const deps = (file) => execFileSync(EMXX, ['-O2', '-fPIC', '-I' + STUBS, '-I' + SRC + '/Run', '-M', file], { encoding: 'utf8' })
    .split(/[\s\\]+/).filter((f) => f.startsWith('/') && !f.startsWith(tmp));
  const headers = new Set([...deps(path.join(tmp, 'model.cpp')), ...deps(SRC + '/Run/support.cpp')]);

  const files = {};
  for (const f of headers) {
    if (f.startsWith(SYS)) files['sysroot' + f.slice(SYS.length)] = fs.readFileSync(f);
    else if (f.startsWith(SRC)) files['simile' + f.slice(SRC.length)] = fs.readFileSync(f);
    // clang's own headers (emsdk's lib/clang) come with clang in the page
  }
  files['stubs/portaudio.h'] = fs.readFileSync(STUBS + '/portaudio.h');

  // support.cpp, compiled by the page's clang with the page's flags (an
  // object from emsdk's newer LLVM need not link with the page's wasm-ld).
  const tree = {};
  const put = (p, data) => {
    const parts = p.split('/'); let t = tree;
    for (const d of parts.slice(0, -1)) t = (t[d] ||= {});
    t[parts.at(-1)] = data;
  };
  for (const [p, data] of Object.entries(files)) put(p, data);
  put('simile/Run/support.cpp', fs.readFileSync(SRC + '/Run/support.cpp'));
  const flags = JSON.parse(fs.readFileSync(path.join(HERE, 'flags.json'), 'utf8')).compile;
  const r = await runClang(['clang++', ...flags, '/simile/Run/support.cpp', '-o', '/support.o'], tree,
    { stdout: () => {}, stderr: () => {} });

  const b64 = (b) => Buffer.from(b).toString('base64');
  const kit = { files: {}, supportO: b64(r['support.o']) };
  for (const [p, data] of Object.entries(files)) kit.files[p] = b64(data);
  fs.writeFileSync(out,
    '// What clang in the page needs to compile a model for Simile\'s engine:\n'
    + '// headers (emsdk sysroot, Simile\'s Run/) and support.cpp compiled.\n'
    + '// Generated by tools/engine/build-browser-tools.sh; do not edit.\n'
    + 'window.SIMILE_MODEL_KIT = ' + JSON.stringify(kit) + ';\n');
  console.log('wrote', out, Object.keys(files).length, 'headers');
} finally {
  fs.rmSync(tmp, { recursive: true });
}
