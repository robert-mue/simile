// Simile's generator for the page: Simile's Prolog and function library and
// this folder's headless.pl and struct_db.pl, as a classic script —
//
//   window.SIMILE_GENERATOR = { files: {path: base64} }
//
// laid out as src/model-compiler.js writes them into SWI-Prolog's file system:
// /simile/Prolog, /simile/Functions, /simile/Makefile, /gen.
//
//   node pack.js <simile src> <out .js>
'use strict';
const fs = require('fs'), path = require('path');
const [src, out] = process.argv.slice(2);
if (!out) { console.error('usage: pack.js <simile src> <out .js>'); process.exit(2); }
const files = {};
function add(from, to, filter) {
  for (const e of fs.readdirSync(from, { withFileTypes: true })) {
    const f = path.join(from, e.name), t = to + '/' + e.name;
    if (e.isDirectory()) add(f, t, filter);
    else if (!filter || filter(e.name)) files[t] = fs.readFileSync(f).toString('base64');
  }
}
add(path.join(src, 'Prolog'), '/simile/Prolog', (n) => n.endsWith('.pl'));
add(path.join(src, 'Functions'), '/simile/Functions');
files['/simile/Makefile'] = fs.readFileSync(path.join(src, 'Makefile')).toString('base64');
for (const f of ['headless.pl', 'struct_db.pl']) {
  files['/gen/' + f] = fs.readFileSync(path.join(__dirname, f)).toString('base64');
}
fs.writeFileSync(out,
  '// Simile\'s code generator (github.com/jal-frezie/simile, GPL v3: its Prolog\n'
  + '// and function library) with tools/engine/generator\'s headless.pl and\n'
  + '// struct_db.pl, for SWI-Prolog in the page. Generated by\n'
  + '// tools/engine/build-browser-tools.sh; do not edit.\n'
  + 'window.SIMILE_GENERATOR = ' + JSON.stringify({ files }) + ';\n');
console.log('wrote', out, Object.keys(files).length, 'files');
